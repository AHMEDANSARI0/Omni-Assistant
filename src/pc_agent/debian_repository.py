"""Deterministic Debian APT repository metadata and optional signing.

Phase 50 turns the already verified Phase 47 ``.deb`` into a small,
static APT repository tree.  The repository contains the package under
``pool/``, ``Packages`` indices for the ``all`` and ``amd64`` architecture
views, a ``Release`` file with MD5/SHA-1/SHA-256/SHA-512 hashes, and a
project manifest that makes the complete tree independently verifiable.

Signing is deliberately delegated to the operator's system GnuPG
installation and an operator-selected key.  No private key material or
passphrase is accepted, stored, or generated by this application.  An
unsigned repository is still hash-verified locally, but is clearly reported
as unsigned.  Building or verifying this static tree does not host it, run
apt/dpkg, install the package, or prove a live Debian/Ubuntu installation.
"""

