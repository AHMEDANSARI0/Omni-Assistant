def _validate_suite(value: str) -> str:
    suite = str(value).strip()
    if _SUITE_RE.fullmatch(suite) is None:
        raise PcAgentError(
            "Debian repository suite must be a lowercase suite name such as stable."
        )
    return suite


def _validate_output_path(root: Path, output: Path) -> Path:
    raw = output.expanduser()
    if raw.is_symlink():
        raise PcAgentError("Debian repository output must not be a symbolic link.")
    destination = raw.resolve()
    if destination.exists():
        raise PcAgentError(
            f"Debian repository output already exists: {destination}."
        )
    if destination == root or destination in root.parents:
        raise PcAgentError("Debian repository output must not be the project root.")
    try:
        relative = destination.relative_to(root)
    except ValueError:
        return destination
    if not relative.parts or relative.parts[0] != "workspace":
        raise PcAgentError(
            "Debian repository output inside the project must be under workspace/."
        )
    return destination


def _validate_gpg_executable(value: str) -> str:
    executable = str(value).strip()
    if (
        not executable
        or len(executable) > 4096
        or "\x00" in executable
        or "\n" in executable
        or "\r" in executable
    ):
        raise PcAgentError("The GnuPG executable value is invalid.")
    return executable


def _validate_signing_key(value: str) -> str:
    key = str(value).strip()
    if (
        not key
        or len(key) > 256
        or key.startswith("-")
        or "\x00" in key
        or "\n" in key
        or "\r" in key
    ):
        raise PcAgentError("The Debian repository signing-key value is invalid.")
    return key


def _validate_gnupg_home(value: Path | None) -> Path | None:
    if value is None:
        return None
    raw = value.expanduser()
    if raw.is_symlink() or not raw.is_dir():
        raise PcAgentError("The GnuPG home directory was not found.")
    return raw.resolve()


def _default_gpg_runner(
    args: tuple[str, ...], input_data: bytes | None, gnupg_home: Path | None
) -> bytes:
    environment = os.environ.copy()
    if gnupg_home is not None:
        environment["GNUPGHOME"] = str(gnupg_home)
    try:
        completed = subprocess.run(
            args,
            input=input_data,
            capture_output=True,
            timeout=30,
            check=False,
            shell=False,
            env=environment,
        )
    except subprocess.TimeoutExpired as exc:
        raise PcAgentError("GnuPG operation timed out.") from exc
    except OSError as exc:
        raise PcAgentError("GnuPG executable could not be started.") from exc
    if len(completed.stdout) > _MAX_GPG_OUTPUT_BYTES:
        raise PcAgentError("GnuPG produced too much output.")
    if completed.returncode != 0:
        raise PcAgentError("GnuPG operation failed.")
    return completed.stdout


def _run_gpg(
    args: Sequence[str],
    *,
    input_data: bytes | None,
    gnupg_home: Path | None,
    runner: GpgRunner | None,
) -> bytes:
    if not args:
        raise PcAgentError("GnuPG operation failed.")
    complete_args = [str(args[0])]
    if gnupg_home is not None:
        complete_args.extend(("--homedir", str(gnupg_home)))
    complete_args.extend(str(item) for item in args[1:])
    active_runner = runner or _default_gpg_runner
    try:
        output = active_runner(tuple(complete_args), input_data, gnupg_home)
    except PcAgentError:
        raise
    except Exception as exc:
        raise PcAgentError("GnuPG operation failed.") from exc
    if not isinstance(output, bytes) or len(output) > _MAX_GPG_OUTPUT_BYTES:
        raise PcAgentError("GnuPG produced invalid output.")
    return output


def _gpg_fingerprint(
    executable: str,
    *,
    selector: str | None,
    secret: bool,
    gnupg_home: Path | None,
    runner: GpgRunner | None,
) -> str:
    args = [
        executable,
        "--batch",
        "--with-colons",
        "--with-fingerprint",
        "--list-secret-keys" if secret else "--list-keys",
    ]
    if selector is not None:
        args.append(selector)
    output = _run_gpg(
        args,
        input_data=None,
        gnupg_home=gnupg_home,
        runner=runner,
    )
    try:
        text = output.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PcAgentError("GnuPG returned an invalid key listing.") from exc
    fingerprints: list[str] = []
    fallback_fingerprints: list[str] = []
    expecting_primary = False
    saw_key_record = False
    for line in text.splitlines():
        fields = line.split(":")
        if not fields:
            continue
        if fields[0] in {"pub", "sec"}:
            saw_key_record = True
            expecting_primary = True
            continue
        if fields[0] in {"sub", "ssb"}:
            expecting_primary = False
            continue
        if len(fields) > 9 and fields[0] == "fpr":
            fingerprint = fields[9].strip().upper()
            if _FINGERPRINT_RE.fullmatch(fingerprint) is None:
                continue
            fallback_fingerprints.append(fingerprint)
            if expecting_primary:
                fingerprints.append(fingerprint)
                expecting_primary = False
    if not saw_key_record and len(set(fallback_fingerprints)) == 1:
        fingerprints = fallback_fingerprints
    if len(set(fingerprints)) != 1:
        raise PcAgentError(
            "The Debian repository signing key must identify exactly one OpenPGP key."
        )
    return fingerprints[0]


def _signing_material(
    release_data: bytes,
    *,
    signing_key: str,
    gnupg_home: Path | None,
    executable: str,
    runner: GpgRunner | None,
) -> tuple[str, bytes, bytes, bytes]:
    key = _validate_signing_key(signing_key)
    fingerprint = _gpg_fingerprint(
        executable,
        selector=key,
        secret=True,
        gnupg_home=gnupg_home,
        runner=runner,
    )
    public_key = _run_gpg(
        (executable, "--batch", "--export", fingerprint),
        input_data=None,
        gnupg_home=gnupg_home,
        runner=runner,
    )
    if not public_key or len(public_key) > _MAX_PUBLIC_KEY_BYTES:
        raise PcAgentError("GnuPG returned an invalid repository public key.")

    common = (
        executable,
        "--batch",
        "--yes",
        "--pinentry-mode",
        "loopback",
        "--digest-algo",
        "SHA512",
        "--local-user",
        fingerprint,
    )
    detached = _run_gpg(
        (*common, "--detach-sign"),
        input_data=release_data,
        gnupg_home=gnupg_home,
        runner=runner,
    )
    clear_signed = _run_gpg(
        (*common, "--clearsign"),
        input_data=release_data,
        gnupg_home=gnupg_home,
        runner=runner,
    )
    if not detached or len(detached) > _MAX_SIGNATURE_BYTES:
        raise PcAgentError("GnuPG returned an invalid detached repository signature.")
    if (
        not clear_signed
        or len(clear_signed) > _MAX_SIGNATURE_BYTES
        or not clear_signed.startswith(b"-----BEGIN PGP SIGNED MESSAGE-----")
    ):
        raise PcAgentError("GnuPG returned an invalid clear-signed repository file.")
    return fingerprint, public_key, detached, clear_signed


def _verify_signatures(
    root: Path,
    suite: str,
    *,
    keyring_data: bytes,
    expected_fingerprint: str,
    executable: str,
    runner: GpgRunner | None,
) -> None:
    suite_root = root / "dists" / suite
    release = suite_root / "Release"
    detached = suite_root / "Release.gpg"
    in_release = suite_root / "InRelease"
    with tempfile.TemporaryDirectory(prefix="pc-agent-gnupg-") as name:
        home = Path(name)
        if os.name == "posix":
            home.chmod(0o700)
        _run_gpg(
            (executable, "--batch", "--import"),
            input_data=keyring_data,
            gnupg_home=home,
            runner=runner,
        )
        actual_fingerprint = _gpg_fingerprint(
            executable,
            selector=None,
            secret=False,
            gnupg_home=home,
            runner=runner,
        )
        if actual_fingerprint != expected_fingerprint:
            raise PcAgentError("Debian repository keyring fingerprint does not match.")
        _run_gpg(
            (executable, "--batch", "--verify", str(detached), str(release)),
            input_data=None,
            gnupg_home=home,
            runner=runner,
        )
        _run_gpg(
            (executable, "--batch", "--verify", str(in_release)),
            input_data=None,
            gnupg_home=home,
            runner=runner,
        )


def _read_control_fields(package_path: Path) -> dict[str, str]:
    package_data = _read_package(package_path)
    members = _parse_ar(package_data)
    control_files = _parse_tar(
        _gunzip_bounded(
            members["control.tar.gz"],
            limit=_MAX_DEBIAN_CONTROL_BYTES * 4,
            label="control archive",
        ),
        label="control archive",
    )
    if "control" not in control_files:
        raise PcAgentError("Debian package control file is missing.")
    return _parse_control(control_files["control"][0])


def _format_fields(fields: Sequence[tuple[str, str]]) -> bytes:
    lines: list[str] = []
    for name, raw_value in fields:
        if _FIELD_NAME_RE.fullmatch(name) is None:
            raise PcAgentError(f"Invalid Debian field name: {name}.")
        value = str(raw_value).replace("\r\n", "\n").replace("\r", "\n")
        value_lines = value.split("\n")
        lines.append(f"{name}: {value_lines[0]}" if value_lines[0] else f"{name}:")
        for continuation in value_lines[1:]:
            lines.append(" ." if continuation == "" else f" {continuation}")
    return ("\n".join(lines) + "\n").encode()


def _parse_fields(data: bytes, *, label: str) -> dict[str, str]:
    if len(data) > _MAX_REPOSITORY_METADATA_BYTES:
        raise PcAgentError(f"Debian repository {label} exceeds the size limit.")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PcAgentError(f"Debian repository {label} is not valid UTF-8.") from exc
    fields: dict[str, str] = {}
    current: str | None = None
    for line in text.splitlines():
        if line == "":
            continue
        if line.startswith(" "):
            if current is None:
                raise PcAgentError(
                    f"Debian repository {label} has an orphan continuation line."
                )
            fields[current] += "\n" + line[1:]
            continue
        if ":" not in line:
            raise PcAgentError(f"Debian repository {label} contains a malformed line.")
        name, value = line.split(":", 1)
        if _FIELD_NAME_RE.fullmatch(name) is None or name in fields:
            raise PcAgentError(f"Debian repository {label} has an invalid field.")
        fields[name] = value.strip()
        current = name
    return fields


def _digests(data: bytes) -> dict[str, str]:
    return {
        "MD5Sum": hashlib.md5(data, usedforsecurity=False).hexdigest(),
        "SHA1": hashlib.sha1(data, usedforsecurity=False).hexdigest(),
        "SHA256": hashlib.sha256(data).hexdigest(),
        "SHA512": hashlib.sha512(data).hexdigest(),
    }


def _packages_bytes(
    control: Mapping[str, str], package_filename: str, package_data: bytes
) -> bytes:
    values = _digests(package_data)
    fields = list(control.items())
    fields.extend(
        (
            ("Filename", package_filename),
            ("Size", str(len(package_data))),
            ("MD5sum", values["MD5Sum"]),
            ("SHA1", values["SHA1"]),
            ("SHA256", values["SHA256"]),
            ("SHA512", values["SHA512"]),
        )
    )
    return _format_fields(fields) + b"\n"


def _gzip_deterministic(data: bytes) -> bytes:
    output = gzip.compress(data, compresslevel=9, mtime=0)
    if len(output) > _MAX_REPOSITORY_METADATA_BYTES:
        raise PcAgentError("Debian repository compressed index exceeds the size limit.")
    return output


def _release_bytes(suite: str, indices: Mapping[str, bytes]) -> bytes:
    hash_names = ("MD5Sum", "SHA1", "SHA256", "SHA512")
    sections: list[tuple[str, str]] = []
    for hash_name in hash_names:
        entries = []
        for relative in sorted(indices):
            data = indices[relative]
            entries.append(f"{_digests(data)[hash_name]} {len(data)} {relative}")
        sections.append((hash_name, "\n" + "\n".join(entries)))
    fields: list[tuple[str, str]] = [
        ("Origin", DEBIAN_PACKAGE_APP_NAME),
        ("Label", DEBIAN_PACKAGE_APP_NAME),
        ("Suite", suite),
        ("Codename", suite),
        ("Date", _RELEASE_DATE),
        ("Architectures", " ".join(DEBIAN_REPOSITORY_ARCHITECTURES)),
        ("Components", DEBIAN_REPOSITORY_COMPONENT),
        (
            "Description",
            "Self-Healing PC Agent deterministic APT repository",
        ),
        ("Acquire-By-Hash", "no"),
        *sections,
    ]
    return _format_fields(fields)


def _pool_relative_path() -> str:
    filename = (
        f"{DEBIAN_PACKAGE_NAME}_{debian_package_version()}_"
        f"{DEBIAN_PACKAGE_ARCHITECTURE}.deb"
    )
    return f"pool/{DEBIAN_REPOSITORY_COMPONENT}/s/{DEBIAN_PACKAGE_NAME}/{filename}"


def _index_relative_paths(suite: str) -> tuple[str, ...]:
    paths: list[str] = []
    for architecture in DEBIAN_REPOSITORY_ARCHITECTURES:
        base = (
            f"{DEBIAN_REPOSITORY_COMPONENT}/binary-{architecture}/Packages"
        )
        paths.extend((base, f"{base}.gz"))
    return tuple(sorted(paths))


def _expected_repository_paths(suite: str, *, signed: bool) -> set[str]:
    suite_root = f"dists/{suite}"
    paths = {
        DEBIAN_REPOSITORY_MANIFEST,
        _pool_relative_path(),
        f"{suite_root}/Release",
    }
    paths.update(
        f"{suite_root}/{relative}" for relative in _index_relative_paths(suite)
    )
    if signed:
        paths.update(
            {
                DEBIAN_REPOSITORY_KEYRING,
                f"{suite_root}/InRelease",
                f"{suite_root}/Release.gpg",
            }
        )
    return paths


def _write_file(root: Path, relative: str, data: bytes) -> None:
    target = root / Path(relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
    target.chmod(0o644)


def _set_epoch_mtime(path: Path) -> None:
    if path.is_symlink():
        raise PcAgentError("Repository output contains a symbolic link.")
    if os.utime in os.supports_follow_symlinks:
        os.utime(path, (0, 0), follow_symlinks=False)
    else:
        # Windows does not implement follow_symlinks for os.utime. The path
        # was just checked not to be a symbolic link, so the portable form
        # cannot follow one here.
        os.utime(path, (0, 0))


def _scan_repository(root: Path) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    total = 0
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise PcAgentError("Debian repository contains a symbolic link.")
        if path.is_dir():
            continue
        if not path.is_file():
            raise PcAgentError("Debian repository contains a non-file entry.")
        relative = path.relative_to(root).as_posix()
        if (
            not relative
            or relative.startswith("../")
            or "/../" in relative
            or "\\" in relative
        ):
            raise PcAgentError("Debian repository contains an unsafe path.")
        size = path.stat().st_size
        if size > _MAX_REPOSITORY_FILE_BYTES:
            raise PcAgentError("Debian repository contains an oversized file.")
        total += size
        if total > _MAX_REPOSITORY_TOTAL_BYTES:
            raise PcAgentError("Debian repository exceeds the total size limit.")
        data = path.read_bytes()
        if len(data) != size:
            raise PcAgentError("Debian repository changed while reading.")
        files[relative] = data
    if not files or len(files) > _MAX_REPOSITORY_FILES:
        raise PcAgentError("Debian repository has an invalid file count.")
    return files


def _manifest_records(files: Mapping[str, bytes]) -> list[dict[str, Any]]:
    return [
        {
            "path": relative,
            "size": len(data),
            "sha256": _sha256_bytes(data),
        }
        for relative, data in sorted(files.items())
        if relative != DEBIAN_REPOSITORY_MANIFEST
    ]


def _parse_manifest(data: bytes) -> dict[str, Any]:
    if len(data) > _MAX_REPOSITORY_MANIFEST_BYTES:
        raise PcAgentError("Debian repository manifest exceeds the size limit.")
    try:
        manifest = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise PcAgentError("Debian repository manifest is not valid JSON.") from exc
    expected = {
        "format",
        "app",
        "package",
        "version",
        "package_version",
        "suite",
        "component",
        "architectures",
        "package_filename",
        "package_size",
        "package_sha256",
        "signed",
        "signing_key_fingerprint",
        "files",
    }
    if not isinstance(manifest, dict) or set(manifest) != expected:
        raise PcAgentError("Debian repository manifest has an unexpected shape.")
    if manifest["format"] != _REPOSITORY_FORMAT:
        raise PcAgentError("Debian repository manifest format is unsupported.")
    if manifest["app"] != DEBIAN_PACKAGE_APP_NAME:
        raise PcAgentError("Debian repository manifest app is unexpected.")
    if manifest["package"] != DEBIAN_PACKAGE_NAME:
        raise PcAgentError("Debian repository manifest package is unexpected.")
    if manifest["version"] != __version__:
        raise PcAgentError("Debian repository version does not match this application.")
    if manifest["package_version"] != debian_package_version():
        raise PcAgentError("Debian repository package version is unexpected.")
    suite = _validate_suite(str(manifest["suite"]))
    if manifest["component"] != DEBIAN_REPOSITORY_COMPONENT:
        raise PcAgentError("Debian repository component is unexpected.")
    if manifest["architectures"] != list(DEBIAN_REPOSITORY_ARCHITECTURES):
        raise PcAgentError("Debian repository architectures are unexpected.")
    if manifest["package_filename"] != _pool_relative_path():
        raise PcAgentError("Debian repository package filename is unexpected.")
    if (
        not isinstance(manifest["package_size"], int)
        or isinstance(manifest["package_size"], bool)
        or manifest["package_size"] <= 0
        or not isinstance(manifest["package_sha256"], str)
        or _SHA256_RE.fullmatch(manifest["package_sha256"]) is None
    ):
        raise PcAgentError("Debian repository package summary is invalid.")
    if not isinstance(manifest["signed"], bool):
        raise PcAgentError("Debian repository signing state is invalid.")
    fingerprint = manifest["signing_key_fingerprint"]
    if manifest["signed"]:
        if not isinstance(fingerprint, str) or _FINGERPRINT_RE.fullmatch(fingerprint) is None:
            raise PcAgentError("Debian repository signing fingerprint is invalid.")
    elif fingerprint is not None:
        raise PcAgentError("Unsigned Debian repository has a signing fingerprint.")

    records = manifest["files"]
    if not isinstance(records, list) or not records:
        raise PcAgentError("Debian repository manifest files are invalid.")
    paths: list[str] = []
    for record in records:
        if not isinstance(record, dict) or set(record) != {"path", "size", "sha256"}:
            raise PcAgentError("Debian repository manifest contains a malformed record.")
        path = record["path"]
        size = record["size"]
        digest = record["sha256"]
        if (
            not isinstance(path, str)
            or path in paths
            or path == DEBIAN_REPOSITORY_MANIFEST
            or path.startswith("/")
            or "\\" in path
            or ".." in Path(path).parts
            or not isinstance(size, int)
            or isinstance(size, bool)
            or size < 0
            or size > _MAX_REPOSITORY_FILE_BYTES
            or not isinstance(digest, str)
            or _SHA256_RE.fullmatch(digest) is None
        ):
            raise PcAgentError("Debian repository manifest contains an invalid record.")
        paths.append(path)
    if paths != sorted(paths):
        raise PcAgentError("Debian repository manifest records are not sorted.")
    manifest["_validated_suite"] = suite
    return manifest


def _verify_release_hashes(
    release_data: bytes, files: Mapping[str, bytes], suite: str
) -> None:
    fields = _parse_fields(release_data, label="Release file")
    expected_scalars = {
        "Origin": DEBIAN_PACKAGE_APP_NAME,
        "Label": DEBIAN_PACKAGE_APP_NAME,
        "Suite": suite,
        "Codename": suite,
        "Date": _RELEASE_DATE,
        "Architectures": " ".join(DEBIAN_REPOSITORY_ARCHITECTURES),
        "Components": DEBIAN_REPOSITORY_COMPONENT,
        "Description": "Self-Healing PC Agent deterministic APT repository",
        "Acquire-By-Hash": "no",
    }
    for field, expected in expected_scalars.items():
        if fields.get(field) != expected:
            raise PcAgentError(f"Debian repository Release field {field} is unexpected.")

    expected_indices = set(_index_relative_paths(suite))
    prefix = f"dists/{suite}/"
    for hash_name in ("MD5Sum", "SHA1", "SHA256", "SHA512"):
        raw_entries = fields.get(hash_name)
        if raw_entries is None:
            raise PcAgentError(f"Debian repository Release is missing {hash_name}.")
        parsed: dict[str, tuple[str, int]] = {}
        for line in raw_entries.splitlines():
            if not line:
                continue
            parts = line.split()
            if len(parts) != 3:
                raise PcAgentError("Debian repository Release hash entry is malformed.")
            digest, size_text, relative = parts
            if relative in parsed:
                raise PcAgentError("Debian repository Release hash entry is duplicated.")
            try:
                size = int(size_text)
            except ValueError as exc:
                raise PcAgentError(
                    "Debian repository Release hash entry has an invalid size."
                ) from exc
            parsed[relative] = (digest.lower(), size)
        if set(parsed) != expected_indices:
            raise PcAgentError("Debian repository Release indexes are unexpected.")
        for relative in expected_indices:
            data = files[f"{prefix}{relative}"]
            expected_digest, expected_size = parsed[relative]
            if (
                len(data) != expected_size
                or _digests(data)[hash_name] != expected_digest
            ):
                raise PcAgentError(
                    f"Debian repository Release {hash_name} does not match {relative}."
                )


def build_debian_repository(
    root_dir: Path,
    package_path: Path,
    output_path: Path,
    *,
    suite: str = DEFAULT_DEBIAN_REPOSITORY_SUITE,
    signing_key: str | None = None,
    gnupg_home: Path | None = None,
    gpg_executable: str = "gpg",
    gpg_runner: GpgRunner | None = None,
) -> DebianRepositoryInfo:
    """Build and verify a static APT repository around a verified ``.deb``."""

    root = root_dir.expanduser().resolve()
    destination = _validate_output_path(root, output_path)
    suite = _validate_suite(suite)
    executable = _validate_gpg_executable(gpg_executable)
    validated_gnupg_home = _validate_gnupg_home(gnupg_home)
    if signing_key is None and validated_gnupg_home is not None:
        raise PcAgentError("A GnuPG home requires a Debian repository signing key.")

    package_info = verify_debian_package(package_path)
    package_data = _read_package(package_info.path)
    if len(package_data) != package_info.package_bytes or _sha256_bytes(
        package_data
    ) != package_info.package_sha256:
        raise PcAgentError("Debian package changed while building the repository.")
    control = _read_control_fields(package_info.path)

    pool_relative = _pool_relative_path()
    packages = _packages_bytes(control, pool_relative, package_data)
    packages_gz = _gzip_deterministic(packages)
    indices: dict[str, bytes] = {}
    repository_indices: dict[str, bytes] = {}
    for relative in _index_relative_paths(suite):
        data = packages_gz if relative.endswith(".gz") else packages
        indices[relative] = data
        repository_indices[f"dists/{suite}/{relative}"] = data
    release_data = _release_bytes(suite, indices)

    signing_fingerprint: str | None = None
    public_key: bytes | None = None
    detached_signature: bytes | None = None
    clear_signed: bytes | None = None
    if signing_key is not None:
        (
            signing_fingerprint,
            public_key,
            detached_signature,
            clear_signed,
        ) = _signing_material(
            release_data,
            signing_key=signing_key,
            gnupg_home=validated_gnupg_home,
            executable=executable,
            runner=gpg_runner,
        )

    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(
        tempfile.mkdtemp(prefix=f".{destination.name}.tmp-", dir=destination.parent)
    )
    try:
        _write_file(temporary, pool_relative, package_data)
        for relative, data in sorted(repository_indices.items()):
            _write_file(temporary, relative, data)
        _write_file(temporary, f"dists/{suite}/Release", release_data)
        if signing_key is not None:
            assert public_key is not None
            assert detached_signature is not None
            assert clear_signed is not None
            _write_file(temporary, DEBIAN_REPOSITORY_KEYRING, public_key)
            _write_file(temporary, f"dists/{suite}/Release.gpg", detached_signature)
            _write_file(temporary, f"dists/{suite}/InRelease", clear_signed)

        staged_files = _scan_repository(temporary)
        manifest = {
            "format": _REPOSITORY_FORMAT,
            "app": DEBIAN_PACKAGE_APP_NAME,
            "package": DEBIAN_PACKAGE_NAME,
            "version": __version__,
            "package_version": debian_package_version(),
            "suite": suite,
            "component": DEBIAN_REPOSITORY_COMPONENT,
            "architectures": list(DEBIAN_REPOSITORY_ARCHITECTURES),
            "package_filename": pool_relative,
            "package_size": len(package_data),
            "package_sha256": package_info.package_sha256,
            "signed": signing_key is not None,
            "signing_key_fingerprint": signing_fingerprint,
            "files": _manifest_records(staged_files),
        }
        manifest_data = (
            json.dumps(manifest, indent=2, sort_keys=True) + "\n"
        ).encode()
        if len(manifest_data) > _MAX_REPOSITORY_MANIFEST_BYTES:
            raise PcAgentError("Debian repository manifest exceeds the size limit.")
        _write_file(temporary, DEBIAN_REPOSITORY_MANIFEST, manifest_data)

        for path in sorted(temporary.rglob("*"), reverse=True):
            _set_epoch_mtime(path)
        _set_epoch_mtime(temporary)

        verify_debian_repository(
            temporary,
            gpg_executable=executable,
            gpg_runner=gpg_runner,
        )
        if destination.exists() or destination.is_symlink():
            raise PcAgentError(
                f"Debian repository output already exists: {destination}."
            )
        temporary.replace(destination)
    finally:
        if temporary.exists() or temporary.is_symlink():
            shutil.rmtree(temporary, ignore_errors=True)

    return verify_debian_repository(
        destination,
        gpg_executable=executable,
        gpg_runner=gpg_runner,
    )


def verify_debian_repository(
    repository_path: Path,
    *,
    gpg_executable: str = "gpg",
    gpg_runner: GpgRunner | None = None,
) -> DebianRepositoryInfo:
    """Verify a Phase 50 APT repository without invoking apt or dpkg."""

    raw = repository_path.expanduser()
    if raw.is_symlink() or not raw.is_dir():
        raise PcAgentError(f"Debian repository was not found: {raw}.")
    root = raw.resolve()
    executable = _validate_gpg_executable(gpg_executable)
    files = _scan_repository(root)
    if DEBIAN_REPOSITORY_MANIFEST not in files:
        raise PcAgentError("Debian repository manifest is missing.")
    manifest = _parse_manifest(files[DEBIAN_REPOSITORY_MANIFEST])
    suite = str(manifest.pop("_validated_suite"))
    signed = bool(manifest["signed"])
    fingerprint = manifest["signing_key_fingerprint"]

    expected_paths = _expected_repository_paths(suite, signed=signed)
    if set(files) != expected_paths:
        raise PcAgentError("Debian repository file inventory is unexpected.")
    expected_records = _manifest_records(files)
    if manifest["files"] != expected_records:
        raise PcAgentError("Debian repository manifest does not match its files.")

    pool_relative = _pool_relative_path()
    package_data = files[pool_relative]
    if (
        len(package_data) != manifest["package_size"]
        or _sha256_bytes(package_data) != manifest["package_sha256"]
    ):
        raise PcAgentError("Debian repository package does not match its manifest.")
    package_path = root / Path(pool_relative)
    package_info = verify_debian_package(package_path)
    if package_info.package_sha256 != manifest["package_sha256"]:
        raise PcAgentError("Debian repository package verification does not match.")

    release_relative = f"dists/{suite}/Release"
    _verify_release_hashes(files[release_relative], files, suite)

    control = _read_control_fields(package_path)
    expected_packages = _packages_bytes(control, pool_relative, package_data)
    expected_packages_gz = _gzip_deterministic(expected_packages)
    for relative in _index_relative_paths(suite):
        data = files[f"dists/{suite}/{relative}"]
        expected = expected_packages_gz if relative.endswith(".gz") else expected_packages
        if data != expected:
            raise PcAgentError(f"Debian repository package index is unexpected: {relative}.")
        if relative.endswith(".gz"):
            decompressed = _gunzip_bounded(
                data,
                limit=_MAX_REPOSITORY_METADATA_BYTES,
                label="compressed package index",
            )
            if decompressed != expected_packages:
                raise PcAgentError(
                    f"Debian repository compressed index is invalid: {relative}."
                )

    if signed:
        if not isinstance(fingerprint, str):
            raise PcAgentError("Debian repository signing fingerprint is invalid.")
        keyring_data = files[DEBIAN_REPOSITORY_KEYRING]
        if not keyring_data or len(keyring_data) > _MAX_PUBLIC_KEY_BYTES:
            raise PcAgentError("Debian repository keyring is invalid.")
        if len(files[f"dists/{suite}/Release.gpg"]) > _MAX_SIGNATURE_BYTES:
            raise PcAgentError("Debian repository detached signature is oversized.")
        in_release = files[f"dists/{suite}/InRelease"]
        if (
            not in_release
            or len(in_release) > _MAX_SIGNATURE_BYTES
            or not in_release.startswith(b"-----BEGIN PGP SIGNED MESSAGE-----")
        ):
            raise PcAgentError("Debian repository InRelease file is invalid.")
        _verify_signatures(
            root,
            suite,
            keyring_data=keyring_data,
            expected_fingerprint=fingerprint,
            executable=executable,
            runner=gpg_runner,
        )

    return DebianRepositoryInfo(
        path=root,
        version=__version__,
        package_version=debian_package_version(),
        suite=suite,
        component=DEBIAN_REPOSITORY_COMPONENT,
        architectures=DEBIAN_REPOSITORY_ARCHITECTURES,
        package_path=package_path,
        package_sha256=package_info.package_sha256,
        release_sha256=_sha256_bytes(files[release_relative]),
        manifest_sha256=_sha256_bytes(files[DEBIAN_REPOSITORY_MANIFEST]),
        file_count=len(files),
        total_bytes=sum(len(data) for data in files.values()),
        signed=signed,
        signing_key_fingerprint=fingerprint if signed else None,
        files=tuple(expected_records),
    )


